/** Two random words, e.g. "wild-willow"; suffix widens the space on collision. */
export function instanceName(suffix = 0): string {
  const pick = (words: string[]) =>
    words[crypto.getRandomValues(new Uint32Array(1))[0] % words.length];
  const name = `${pick(ADJECTIVES)}-${pick(NOUNS)}`;
  return suffix > 0 ? `${name}-${suffix}` : name;
}
